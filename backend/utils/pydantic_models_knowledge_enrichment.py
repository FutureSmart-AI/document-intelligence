"""Request/response models for the Enrichment Analytics endpoints
(routers/knowledge_enrichment_health.py) — see
docs/plan/enrichment-analytics/plan.md.

Shape deliberately mirrors utils/pydantic_models_knowledge_health.py (the chat
Agent Health contract) so one screen can render both with the same components:
a usage block, a quality block, a perf block, a cost block and a trend block,
each carrying the same field names where the meaning is the same. Where the
meaning differs, the name differs too — chat counts `total_queries`, enrichment
counts `total_documents`, and pretending otherwise would be worse than an
inconsistency.

Three fields have no chat equivalent, because they answer the questions the
chat dashboard never had to ask:

- `avg_ms_per_1k_chars` — enrichment latency scales with document length, so raw
  avg_ms compares the documents a model happened to receive, not the models.
- `field_coverage` / `by_field` — the proportion of the configured extraction
  schema that came back populated. The standard completeness measure for a
  structured-extraction pipeline, and the only quality signal available without
  a judge model.
- `used_fallback` / `fallback_count` — a document served by the fallback model
  instead of the requested one.
"""

from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Ingest (worker -> API)
# ---------------------------------------------------------------------------

class FieldOutcome(BaseModel):
    """One configured extraction field and whether this attempt filled it."""

    field_name: str
    level: Optional[str] = None          # "document" | "chunk"
    populated: bool = False
    # How many values came back (a List[str] field can be populated with 1 or 20).
    value_count: int = 0


class EnrichmentEventRequest(BaseModel):
    """One enrichment attempt on one document.

    `event_key` is generated by the worker per attempt so a retried POST is
    idempotent — the insert is ON CONFLICT DO NOTHING on that column. The same
    role `chat_id` plays for chat health events.

    `status` is `success` | `validation_failed` | `error`.
    `validation_failed` is kept distinct from `error` on purpose: the model
    replied and the reply did not satisfy the schema (or came back entirely
    empty/placeholder), which is a different problem from the call failing, and
    it is the failure class a model comparison most needs to see.
    """

    event_key: str
    object_id: Optional[str] = None
    owner_id: Optional[str] = None
    trace_id: Optional[str] = None

    document_name: Optional[str] = None
    char_count: int = 0
    chunk_count: int = 0

    # How the document was read: text_based | scanned | layout_aware | visual |
    # mixed. Optional because a worker older than migration 046 does not send it;
    # those rows carry NULL and are excluded from mode comparisons rather than
    # being lumped into whichever mode happens to be the default.
    #
    # Worth sending even though the mode is already on the document row: the
    # analytics side must group enrichment ATTEMPTS by the mode each attempt ran
    # against, and a document re-ingested in a different mode would otherwise
    # retro-label its own earlier attempts.
    document_processing_mode: Optional[str] = None

    # LangSmith RUN id for this attempt (migration 047). Optional because a worker
    # older than 047, or one running with tracing off, does not send it -- those
    # rows keep the local price-catalog estimate and are skipped by the finalizer
    # rather than guessed at. NOT the same as trace_id above: read_run resolves
    # only the run id.
    langsmith_run_id: Optional[str] = None

    status: str
    failure_category: Optional[str] = None
    failure_detail: Optional[str] = None

    enrichment_strategy: Optional[int] = None
    enrichment_strategy_name: Optional[str] = None

    requested_provider: Optional[str] = None
    requested_model: Optional[str] = None
    provider: Optional[str] = None
    model: Optional[str] = None
    used_fallback: bool = False
    fallback_reason: Optional[str] = None

    duration_ms: int = 0
    retry_count: int = 0

    input_tokens: int = 0
    output_tokens: int = 0
    total_tokens: int = 0

    fields_configured: int = 0
    fields_populated: int = 0
    field_data: List[FieldOutcome] = Field(default_factory=list)

    key_type: Optional[str] = None


class EnrichmentEventResponse(BaseModel):
    recorded: bool
    event_key: str
    # False when the row already existed (a retried POST) — not an error.
    duplicate: bool = False


# ---------------------------------------------------------------------------
# Shared read blocks
# ---------------------------------------------------------------------------

class EnrichmentUsageBlock(BaseModel):
    total_documents: int
    unique_documents: int
    total_chars: int
    total_chunks: int
    bucket: str = "day"
    per_day: List[Dict[str, Any]] = Field(default_factory=list)


class FailureCategoryCount(BaseModel):
    failure_category: Optional[str]
    count: int
    pct_of_failures: float


class EnrichmentQualityBlock(BaseModel):
    succeeded: int
    validation_failed: int
    error: int
    success_rate: float
    # Mean of (fields_populated / fields_configured) over successful attempts
    # only — a failed attempt has no coverage to average, and folding its 0 in
    # would double-count the failure as a quality problem too.
    avg_field_coverage: Optional[float] = None
    by_failure_category: List[FailureCategoryCount] = Field(default_factory=list)


class SlowDocument(BaseModel):
    object_id: Optional[str]
    document_name: Optional[str]
    duration_ms: int
    char_count: int
    ms_per_1k_chars: Optional[float]
    model: Optional[str]
    trace_id: Optional[str] = None


class EnrichmentPerfBlock(BaseModel):
    avg_ms: float
    p50_ms: float
    p95_ms: float
    # None when no attempt in the window reported a char_count.
    avg_ms_per_1k_chars: Optional[float] = None
    slowest: List[SlowDocument] = Field(default_factory=list)


class ByModelCost(BaseModel):
    provider: Optional[str]
    model: Optional[str]
    documents: int
    cost: Optional[float]
    cost_complete: bool = True


class ExpensiveDocument(BaseModel):
    object_id: Optional[str]
    document_name: Optional[str]
    total_tokens: int
    cost_usd: Optional[float]
    model: Optional[str]
    trace_id: Optional[str] = None


class EnrichmentCostBlock(BaseModel):
    """Cost is computed at read time from `usage_service_pricing`, not stored on
    the row — see the migration 043 docstring.

    `cost_complete` is False when at least one (provider, model) in the window
    has no pricing row. That model's line is `null`, never `0`, and
    `total_cost` is then a documented lower bound. Same honesty rule as
    chat/pricing.py's; note the usage-analytics path does the opposite and
    silently reports 0 (see docs/modules/analytics-data-sources.md).
    """

    total_cost: Optional[float]
    avg_cost_per_document: Optional[float]
    total_tokens: int
    input_tokens: int
    output_tokens: int
    cost_complete: bool
    by_model: List[ByModelCost] = Field(default_factory=list)
    most_expensive: List[ExpensiveDocument] = Field(default_factory=list)


class EnrichmentTrendBlock(BaseModel):
    prev_success_rate: Optional[float]
    success_rate_delta: Optional[float]
    prev_avg_ms: Optional[float]
    avg_ms_delta: Optional[float]
    prev_total_cost: Optional[float]
    cost_delta: Optional[float]
    prev_avg_field_coverage: Optional[float]
    field_coverage_delta: Optional[float]
    direction: str


class EnrichmentScorecardResponse(BaseModel):
    knowledge_id: str
    period: str
    since: str
    until: str
    previous_since: str
    usage: EnrichmentUsageBlock
    quality: EnrichmentQualityBlock
    perf: EnrichmentPerfBlock
    cost: EnrichmentCostBlock
    trend: EnrichmentTrendBlock


# ---------------------------------------------------------------------------
# Model comparison
# ---------------------------------------------------------------------------

class ModelStat(BaseModel):
    """One row of the model-comparison table.

    The enrichment analogue of chat's `NodeStat`, re-cut by
    (provider, model, strategy) instead of (node_name, model) — enrichment has
    no graph nodes, but it does have strategies, and the same model can behave
    very differently under strategy 1 (one LLM call per document AND per chunk)
    versus strategy 2 (pre-split, single call).

    Read `success_rate` before anything else in this row. A model that fails
    often looks cheap and fast on every other column, because the columns only
    describe the attempts that produced numbers.
    """

    provider: Optional[str]
    model: Optional[str]
    enrichment_strategy_name: Optional[str]

    documents: int
    succeeded: int
    validation_failed: int
    error: int
    success_rate: float

    avg_ms: float
    p50_ms: float
    p95_ms: float
    avg_ms_per_1k_chars: Optional[float]

    total_tokens: int
    avg_tokens_per_document: float

    total_cost: Optional[float]
    avg_cost_per_document: Optional[float]
    cost_complete: bool

    avg_field_coverage: Optional[float]
    fallback_count: int


class FieldCoverageStat(BaseModel):
    """Per-configured-field coverage across the window.

    Answers "which fields does this model keep failing to extract" — the
    actionable form of a low coverage number, since the fix is usually a field
    description or a sample-values list, not a different model.
    """

    field_name: str
    level: Optional[str]
    documents: int
    populated: int
    coverage_pct: float
    avg_value_count: float


class ModeModelStat(BaseModel):
    """One cell of the mode x model cross-tab — the internal-experiment view.

    Why this exists as its own block rather than a `mode` column on ModelStat:
    the two factors are CONFOUNDED by default. `get_enrichment_config` level 2
    substitutes a stronger model for every mode except text_based, so the
    default path only ever produces (text_based, weak) and (layout_aware,
    strong). A table cut by model alone therefore cannot tell "this model is
    better" from "this model only ever saw the easier input", and a table cut by
    mode alone cannot tell "this mode is better" from "this mode got the better
    model". Only the cross-tab separates them.

    Measured 2026-08-27 on one bank statement with printed control totals
    (docs/plan/enrichment-analytics/mode-model-experiment.md): correct
    transaction signs turned out to be an INTERACTION, not a main effect — one
    of four cells scored 95.9% while the other three sat at 8-12%, including
    the strong model on text_based input. Both single-factor readings looked
    proven from the diagonal and both were wrong.

    A cell whose `documents` is small is a cell, not a finding. The default
    routing means the off-diagonal cells stay empty until somebody pins
    `enrichment_model` on the knowledge base, so expect two populated cells and
    two zeros unless an experiment is running.
    """

    document_processing_mode: Optional[str]
    provider: Optional[str]
    model: Optional[str]

    documents: int
    succeeded: int
    success_rate: float

    avg_ms: float
    avg_ms_per_1k_chars: Optional[float]
    avg_char_count: Optional[float]

    total_cost: Optional[float]
    cost_complete: bool

    # Non-emptiness. Present for continuity with the existing table, but it is
    # the column that hid the 11x gap above — read the two below instead.
    avg_field_coverage: Optional[float]
    # NULL when nothing in this cell has been validated. Distinct from 0.0.
    avg_correctness: Optional[float]
    avg_completeness: Optional[float]
    validated_documents: int
    # How many documents in THIS cell carry a completeness score. Reported
    # separately from validated_documents because completeness is gated by its
    # own env flag: a cell can be fully correctness-validated and have zero
    # completeness scores. Without this a reader cannot tell "0.9 completeness
    # over 40 documents" from "over one", nor either from "the metric is off".
    completeness_scored_documents: int = 0
    # Documents in this cell whose validation was ATTEMPTED and produced no
    # score. Subtract from validated_documents to get the number actually
    # scored. Non-zero here means the cell's averages rest on fewer documents
    # than validated_documents suggests, so a comparison across cells that
    # ignores this column is comparing different sample sizes.
    validation_errors: int = 0


class ModelComparisonResponse(BaseModel):
    knowledge_id: str
    period: str
    since: str
    until: str
    models: List[ModelStat] = Field(default_factory=list)
    by_field: List[FieldCoverageStat] = Field(default_factory=list)
    # The cross-tab. Empty on windows whose rows predate migration 046, since
    # those carry no mode.
    by_mode_model: List[ModeModelStat] = Field(default_factory=list)
    # Whether completeness may be READ from this response at all. Consumers must
    # branch on this before rendering or ranking: when `enabled` is false, or
    # `scored_documents` is 0, every avg_completeness above is NULL because the
    # metric did not run — NOT because the extractions were incomplete. Coercing
    # that NULL to 0.0 would invent the worst possible score for every model and
    # invert any ranking built on it.
    completeness: "CompletenessAvailability" = Field(
        default_factory=lambda: CompletenessAvailability()
    )


class CompletenessAvailability(BaseModel):
    """Why completeness is or is not readable in this window.

    Exists because NULL is ambiguous three ways and the caller has to tell them
    apart: the metric is switched off, it is on but nothing has been scored yet,
    or it ran and legitimately could not score these documents.
    """

    enabled: bool = False
    scored_documents: int = 0
    # "disabled" | "no_scored_documents" | "available"
    status: str = "disabled"
    # One human-readable clause for a UI to show in place of a number.
    reason: Optional[str] = (
        "Completeness is disabled (EXTRACTION_COMPLETENESS_ENABLED)."
    )


