# Per-document drill-down
# ---------------------------------------------------------------------------

class DocumentRow(BaseModel):
    event_key: str
    object_id: Optional[str]
    document_name: Optional[str]
    created_at: str

    status: str
    failure_category: Optional[str]
    failure_detail: Optional[str]

    requested_model: Optional[str]
    provider: Optional[str]
    model: Optional[str]
    used_fallback: bool
    fallback_reason: Optional[str]
    enrichment_strategy_name: Optional[str]

    char_count: int
    chunk_count: int
    duration_ms: int
    ms_per_1k_chars: Optional[float]
    retry_count: int

    input_tokens: int
    output_tokens: int
    total_tokens: int
    # The figure to display. Prefers the LangSmith-finalized cost when one was
    # stored, and falls back to a read-time estimate from usage_service_pricing.
    # `cost_source` says which you got — without it the two are
    # indistinguishable, and they disagree: LangSmith prices the attempt that
    # actually ran, while the estimate multiplies stored tokens by a catalog
    # rate and silently reads 0/None for a model missing from the catalog.
    cost_usd: Optional[float]
    cost_source: Optional[str] = None  # "langsmith" | "estimate" | None
    # False when the estimate was used because no finalized figure exists yet.
    cost_complete: bool = False
    # The run id the finalizer keys on. NULL means this row's cost can never be
    # finalized — no amount of retrying creates a run id after the fact — so a
    # NULL here is the marker for a permanent hole in cost history, not a
    # pending state. Distinct from `trace_id`, which is an OpenTelemetry id and
    # is NOT accepted by LangSmith's read_run.
    langsmith_run_id: Optional[str] = None

    fields_configured: int
    fields_populated: int
    # Coverage is NON-EMPTINESS, not correctness. Render it next to the
    # validation scores below, never as a quality figure on its own: the same
    # document read two ways scored an identical 100% here across an 11x
    # accuracy gap (docs/plan/enrichment-analytics/mode-model-experiment.md).
    field_coverage: Optional[float]
    field_data: Optional[List[Dict[str, Any]]] = None

    # How the document was read. NULL on rows written before migration 046, and
    # on those the UI must show "unknown", not the default mode.
    document_processing_mode: Optional[str] = None

    # Validation — NULL means not validated. Do NOT coalesce to 0.0 when
    # rendering: 0.0 means everything checked was wrong.
    validation_status: Optional[str] = None
    validation_model: Optional[str] = None
    correctness_score: Optional[float] = None
    completeness_score: Optional[float] = None
    validation_ms: Optional[int] = None
    validation_cost_usd: Optional[float] = None

    trace_id: Optional[str] = None


class DocumentsResponse(BaseModel):
    knowledge_id: str
    period: str
    since: str
    until: str
    total_matching: int
    limit: int
    offset: int
    documents: List[DocumentRow] = Field(default_factory=list)


