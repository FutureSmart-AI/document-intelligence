"""Server-side client for the existing collection/ingestion/search/chat API.

Requires only Python's standard library. Never place its private credential in
browser code. An optional private env file is the one generated by configure.py.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import time
import urllib.error
import urllib.request
import uuid


def run(base_url, api_key, owner, file, *, collection_name='API service example'):
    """Exercise the product API; this client contains no ingestion or RAG engine."""
    def request(method, path, body=None, content_type='application/json'):
        data = json.dumps(body).encode() if isinstance(body, dict) else body
        req = urllib.request.Request(base_url.rstrip('/')+'/'+path.lstrip('/'), method=method, data=data,
                                     headers={'x-api-key':api_key, 'Content-Type':content_type})
        try:
            with urllib.request.urlopen(req, timeout=240) as response:
                return json.load(response)
        except urllib.error.HTTPError as exc:
            # Do not echo headers, credentials, or provider error bodies.
            raise RuntimeError(f'{method} {path} returned HTTP {exc.code}') from None

    collection = request('POST', 'v1', {'owner_id':owner, 'collection_name':collection_name})['knowledge_id']
    request('PUT', f'v1/{collection}/config', {})
    boundary = 'document-intelligence-'+uuid.uuid4().hex
    data = (f'--{boundary}\r\nContent-Disposition: form-data; name="document_processing_mode"\r\n\r\ntext_based\r\n'
            f'--{boundary}\r\nContent-Disposition: form-data; name="file"; filename="{file.name}"\r\n'
            'Content-Type: text/plain\r\n\r\n').encode()+file.read_bytes()+f'\r\n--{boundary}--\r\n'.encode()
    uploaded = request('POST', f'v1/{collection}/documents', data, f'multipart/form-data; boundary={boundary}')
    object_id = uploaded['object_id']
    deadline = time.monotonic()+600
    while True:
        status = request('GET', f'v1/{collection}/documents/{object_id}/status')
        state = status.get('processing_status') or status.get('status')
        if state=='completed':break
        if state=='failed':raise RuntimeError('Document processing failed; inspect the API/worker logs privately')
        if time.monotonic()>deadline:raise TimeoutError('Document did not complete within ten minutes')
        time.sleep(3)
    question = "What is Northstar Research's daily meal reimbursement limit, and when must receipts be submitted?"
    retrieved = request('POST', f'v1/{collection}/search', {'query':question, 'object_ids':[object_id], 'num_chunks':3, 'mode':'hybrid'})
    chunks = retrieved.get('chunks', [])
    if not chunks or any(chunk.get('object_id')!=object_id for chunk in chunks):
        raise RuntimeError('Retrieved sources did not respect the selected document')
    normalized = ' '.join(file.read_text(encoding='utf-8').split())
    source_matches = any(normalized in ' '.join(chunk.get('chunk_text','').split()) for chunk in chunks)
    if not source_matches:raise RuntimeError('Retrieved text does not contain the original fixture')
    answer = request('POST', f'v1/{collection}/chat', {'query':question, 'stream':False})
    answer_text = answer.get('response', '')
    if not (('2,450' in answer_text or '2450' in answer_text) and ('fourteen' in answer_text.lower() or '14' in answer_text)):
        raise RuntimeError('The example answer did not contain both expected fixture facts')
    if object_id not in json.dumps(answer.get('data', {}).get('knowledge', {})):
        raise RuntimeError('Answer did not identify the uploaded source')
    return {'knowledge_id':collection, 'object_id':object_id, 'processing_status':state,
            'fixture_sha256':hashlib.sha256(file.read_bytes()).hexdigest(),
            'source_text_matches_fixture':source_matches, 'search':retrieved, 'chat':answer}


if __name__=='__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--base-url', default='http://localhost:8000', help='Direct API base; include a proxy prefix only when your deployment uses one')
    parser.add_argument('--env-file', type=Path, help='Private configuration generated by deploy/configure.py')
    parser.add_argument('--file', type=Path, default=Path(__file__).with_name('northstar-policy.txt'))
    parser.add_argument('--collection-name', default='API service example')
    args = parser.parse_args()
    config = {}
    if args.env_file:
        for line in args.env_file.read_text(encoding='utf-8').splitlines():
            if line and not line.lstrip().startswith('#') and '=' in line:
                key, value = line.split('=', 1)
                config[key] = value
    key = os.getenv('DI_API_KEY') or config.get('FASTAPI_SECRET_KEY')
    owner = os.getenv('DI_OWNER_ID') or config.get('STANDALONE_OWNER_EMAIL', 'owner@example.test')
    if not key:parser.error('Set DI_API_KEY privately or supply --env-file; do not put a key in command arguments')
    print(json.dumps(run(args.base_url, key, owner, args.file, collection_name=args.collection_name), indent=2))
